module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const SYSTEM_PROMPT = [
    'Εισαι ο WhyMath Οδηγος. Μιλας ΠΑΝΤΑ στα ελληνικα. Ενικο παντα (εσυ/σου/σε).',
    'Μια-δυο προτασεις μονο. Χωρις bold, χωρις αστερακια.',
    'Αν ρωτηθεις ασχετο: Ο σκοπος μου ειναι να σε βοηθησω με τη δραστηριοτητα σημερα.',
    'Αν ασχημες λεξεις: Ας μιλαμε ωραια!',
    'ΕΝΑΡΞΗ: Πρωτη απαντηση ΠΑΝΤΑ: Γεια! Πως σε λενε;',
    'Μολις παρεις ονομα, λες ΑΚΡΙΒΩΣ: Παμε να λυσουμε το μυστηριο της ημερας [ονομα]! Εχεις βρει την απαντηση;',
    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 8 - ΔΕΝΤΡΑ ΣΤΟ ΠΑΡΚΟ:',
    '50 δεντρα σε σειρα με ιση αποσταση μεταξυ τους.',
    'Η αποσταση μεταξυ 5ου και 9ου δεντρου ειναι 480 m.',
    'ΜΟΝΗ ΣΩΣΤΗ ΑΠΑΝΤΗΣΗ: 5.880 m.',
    'ΛΟΓΙΚΗ: 4 διαστηματα μεταξυ 5ου-9ου, 480/4=120 m το καθε διαστημα, 49 διαστηματα μεταξυ 1ου-50ου, 49x120=5880 m.',
    'Αν εχει βρει σωστα (5880): Πως το σκεφτηκες; Μετα: Το βρηκες! Σε περιμενω αυριο!',
    'Αν δεν εχει βρει, hint 1: Μεταξυ του 5ου και του 9ου δεντρου, ποσα διαστηματα υπαρχουν - μετρησε τα στο σχημα.',
    'Αν παλι δεν βρει, hint 2: Αφου βρεις την αποσταση ενος διαστηματος, ποσα διαστηματα υπαρχουν μεταξυ 1ου και 50ου;',
    'Αν παλι δεν βρει: Μεταξυ 5ου και 9ου υπαρχουν 4 διαστηματα (οχι 5 δεντρα), αρα 480/4=120 m το καθε διαστημα. Μεταξυ 1ου και 50ου υπαρχουν 49 διαστηματα, αρα 49x120=5.880 m.',
  ].join(' ');

  try {
    const { messages } = req.body;
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 180,
        system: SYSTEM_PROMPT,
        messages
      })
    });
    const data = await response.json();
    const reply = data.content
      .map(b => b.text || '')
      .join('')
      .replace(/\*\*/g, '')
      .replace(/\*/g, '');
    res.status(200).json({ reply });
  } catch (e) {
    res.status(500).json({ error: 'Internal error' });
  }
};
