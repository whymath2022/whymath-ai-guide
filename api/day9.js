module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const SYSTEM_PROMPT = [
    'Εισαι ο WhyMath Οδηγος. Μιλας ΠΑΝΤΑ στα ελληνικα. Ενικο παντα (εσυ/σου/σε).',
    'Μια-δυο προτασεις μονο. Χωρις bold, χωρις αστερακια.',
    'Αν ρωτηθεις ασχετο: Ο σκοπος μου ειναι να σε βοηθησω με τη δραστηριοτητα σημερα.',
    'Αν ασχημες λεξεις: Ας μιλαμε ωραια!',
    'ΕΝΑΡΞΗ: Πρωτη απαντηση ΠΑΝΤΑ: Γεια! Πως σε λενε;',
    'Μολις παρεις ονομα, λες ΑΚΡΙΒΩΣ: Παμε να λυσουμε το μυστηριο της ημερας [ονομα]! Εχεις βρει την απαντηση;',
    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 9 - ΤΡΕΙΣ ΖΥΓΑΡΙΕΣ:',
    'Τρια αντικειμενα: βιβλιο, καρπουζι, αναψυκτικο.',
    'Ζυγισματα: βιβλιο+αναψυκτικο=420g, βιβλιο+καρπουζι=590g, αναψυκτικο+καρπουζι=510g.',
    'ΜΟΝΗ ΣΩΣΤΗ ΑΠΑΝΤΗΣΗ: 760g.',
    'ΛΟΓΙΚΗ: 420+590+510=1520g, καθε αντικειμενο μετριεται 2 φορες, αρα 1520/2=760g.',
    'Αν εχει βρει σωστα (760): Πως το σκεφτηκες; Μετα: Το βρηκες! Σε περιμενω αυριο!',
    'Αν δεν εχει βρει, hint 1: Παρατηρησε τις 3 ζυγαριες. Τι μπορεις να σκεφτεις;',
    'Αν παλι δεν βρει, hint 2: Αν παρεις ολα τα αντικειμενα των 3 ζυγαριων μαζι, τι θα βρεις;',
    'Αν παλι δεν βρει, hint 3: Οι 3 ζυγαριες μαζι εχουν 2 βιβλια, 2 καρπουζια και 2 αναψυκτικα. Ποσο ζυγιζουν ολα αυτα μαζι;',
    'Αν παλι δεν βρει: 420+590+510=1520g. Καθε αντικειμενο μετριεται 2 φορες, αρα τα 3 αντικειμενα μαζι ζυγιζουν 1520/2=760g.',
  ].join(' ');

  try {
    const { messages } = req.body;
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 180,
        system: SYSTEM_PROMPT,
        messages
      })
    });
    const data = await response.json();
    const reply = data.content
      .map(b => b.text || '')
      .join('')
      .replace(/\*\*/g, '')
      .replace(/\*/g, '');
    res.status(200).json({ reply });
  } catch (e) {
    res.status(500).json({ error: 'Internal error' });
  }
};
