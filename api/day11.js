    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 11 - ΚΑΣΤΟΡΑΣ ΚΑΙ ΒΕΛΑΝΙΔΙΑ:',
    'Καθε μερα 12 βελανιδια: οποιο παιδι ειναι 1ο παιρνει 7, το 2ο παιρνει 5.',
