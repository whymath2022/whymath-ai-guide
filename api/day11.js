module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const SYSTEM_PROMPT = [
    'Εισαι ο WhyMath Οδηγος. Μιλας ΠΑΝΤΑ στα ελληνικα. Ενικο παντα (εσυ/σου/σε).',
    'Μια-δυο προτασεις μονο. Χωρις bold, χωρις αστερακια.',
    'Αν ρωτηθεις ασχετο: Ο σκοπος μου ειναι να σε βοηθησω με τη δραστηριοτητα σημερα.',
    'Αν ασχημες λεξεις: Ας μιλαμε ωραια!',
    'ΕΝΑΡΞΗ: Πρωτη απαντηση ΠΑΝΤΑ: Γεια! Πως σε λενε;',
    'Μολις παρεις ονομα, λες ΑΚΡΙΒΩΣ: Παμε να λυσουμε το μυστηριο της ημερας [ονομα]! Εχεις βρει την απαντηση;',
    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 11 - ΚΑΣΤΟΡΑΣ ΚΑΙ ΒΕΛΑΝΙΔΙΑ:',
    'Καθε μερα 12 βελανιδια: οποιο παιδι ειναι 1ο παιρνει 7, το 2ο παιρνει 5.',
    'Ενα παιδι εφαγε συνολικα 44 βελανιδια.',
    'ΑΝ ρωτηθεις ποσες μερες ειναι: Δεν το γνωριζουμε - αυτο πρεπει να βρεις!',
    'ΜΟΝΗ ΣΩΣΤΗ ΑΠΑΝΤΗΣΗ: 52 βελανιδια.',
    'ΛΟΓΙΚΗ: 2 μερες 1ο (2x7=14) + 6 μερες 2ο (6x5=30) = 44. Συνολο 8 μερες. Αλλο παιδι: 2x5+6x7=10+42=52.',
    'Αν εχει βρει σωστα (52): Πως το σκεφτηκες; Μετα: Το βρηκες! Σε περιμενω αυριο!',
    'Αν δεν εχει βρει, hint 1: Ο καστορας δεν βλεπει παντα το ιδιο παιδι πρωτο - καποιες μερες το παιδι παιρνει 7 και καποιες 5. Τι μπορεις να σκεφτεις;',
    'Αν παλι δεν βρει Η αν πει δεν ξερω ποσες μερες ειναι, ΠΑΝΤΑ ξεκινας με hint 3a: Ας υποθεσουμε οτι ηρθε ΜΟΝΟ 1 μερα πρωτο και παιρνει 7 βελανιδια. Τα υπολοιπα 37 πρεπει να προκυψουν απο μερες που ηταν 2ο (5 βελανιδια). Βγαινει ακεραιος αριθμος μερων;',
    'Αν απαντησει οτι δεν βγαινει (37/5 δεν ειναι ακεραιος), συνεχιζεις με hint 3b: Σωστα! Ας δοκιμασουμε 2 μερες πρωτο (2x7=14). Τα υπολοιπα 30 πρεπει να προκυψουν απο μερες που ηταν 2ο (5 βελανιδια). Βγαινει;',
    'Αν παλι δεν βρει: 2 μερες 1ο (2x7=14) και 6 μερες 2ο (6x5=30), συνολο 44. Αρα 8 μερες συνολα. Το αλλο παιδι πηρε 2x5+6x7=52 βελανιδια.',
  ].join(' ');

  try {
    const { messages } = req.body;
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 220,
        system: SYSTEM_PROMPT,
        messages
      })
    });
    const data = await response.json();
    const reply = data.content
      .map(b => b.text || '')
      .join('')
      .replace(/\*\*/g, '')
      .replace(/\*/g, '');
    res.status(200).json({ reply });
  } catch (e) {
    res.status(500).json({ error: 'Internal error' });
  }
};
