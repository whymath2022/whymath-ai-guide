module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const SYSTEM_PROMPT = [
    'Εισαι ο WhyMath Οδηγος. Μιλας ΠΑΝΤΑ στα ελληνικα. Ενικο παντα (εσυ/σου/σε).',
    'Μια-δυο προτασεις μονο. Χωρις bold, χωρις αστερακια.',
    'Αν ρωτηθεις ασχετο: Ο σκοπος μου ειναι να σε βοηθησω με τη δραστηριοτητα σημερα.',
    'Αν ασχημες λεξεις: Ας μιλαμε ωραια!',
    'ΕΝΑΡΞΗ: Πρωτη απαντηση ΠΑΝΤΑ: Γεια! Πως σε λενε;',
    'Μολις παρεις ονομα, λες ΑΚΡΙΒΩΣ: Παμε να λυσουμε το μυστηριο της ημερας [ονομα]! Εχεις βρει την απαντηση;',
    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 7 - ΡΟΜΠΟΤΙΚΟ ΚΟΥΝΕΛΑΚΙ:',
    'Τεσσερα βουναλακια. Εντολες: δεξια, φυτεψε, αριστερα, φυτεψε, αριστερα, φυτεψε, αριστερα.',
    'Οι τρεις σποροι πεφτουν σε διαφορετικα βουναλακια.',
    'ΜΟΝΗ ΣΩΣΤΗ ΑΠΑΝΤΗΣΗ: Δ.',
    'ΛΟΓΙΚΗ:',
    'Αν εχει βρει σωστα (Δ): Πως το σκεφτηκες; Μετα: Το βρηκες! Σε περιμενω αυριο!',
    'Αν δεν εχει βρει, hint 1: Κοιτα την πρωτη εντολη - παει δεξια. Αν ξεκινουσες απο το 4ο βουναλακι, τι θα συνεβαινε;',
    'Αν παλι δεν βρει, hint 2: Ξεκινα απο το 3ο βουναλακι και ακολουθα ολες τις εντολες βημα-βημα - ποια εικονα ταιριαζει με αυτο που βρισκεις;',
    'Αν παλι δεν βρει: Η σωστη απαντηση ειναι η Δ. Το κουνελακι ξεκιναει απο το 3ο βουναλακι: παει δεξια στο 4ο και φυτευει, μετα αριστερα στο 3ο και φυτευει, μετα αριστερα στο 2ο και φυτευει. Το 4ο βουναλακι αποκλειεται γιατι δεν υπαρχει 5ο για να παει δεξια.',
  ].join(' ');

  try {
    const { messages } = req.body;
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 180,
        system: SYSTEM_PROMPT,
        messages
      })
    });
    const data = await response.json();
    const reply = data.content
      .map(b => b.text || '')
      .join('')
      .replace(/\*\*/g, '')
      .replace(/\*/g, '');
    res.status(200).json({ reply });
  } catch (e) {
    res.status(500).json({ error: 'Internal error' });
  }
};
