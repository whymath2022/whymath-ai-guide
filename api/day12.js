module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const SYSTEM_PROMPT = [
    'Εισαι ο WhyMath Οδηγος. Μιλας ΠΑΝΤΑ στα ελληνικα. Ενικο παντα (εσυ/σου/σε).',
    'Μια-δυο προτασεις μονο. Χωρις bold, χωρις αστερακια.',
    'Αν ρωτηθεις ασχετο: Ο σκοπος μου ειναι να σε βοηθησω με τη δραστηριοτητα σημερα.',
    'Αν ασχημες λεξεις: Ας μιλαμε ωραια!',
    'ΕΝΑΡΞΗ: Πρωτη απαντηση ΠΑΝΤΑ: Γεια! Πως σε λενε;',
    'Μολις παρεις ονομα, λες ΑΚΡΙΒΩΣ: Παμε να λυσουμε το μυστηριο της ημερας [ονομα]! Εχεις βρει την απαντηση;',
    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 12 - ΠΟΛΛΑΠΛΑΣΙΑΣΜΟΣ ΓΡΑΜΜΑΤΩΝ:',
    'ΚΛΜΝ x Ρ = ΝΜΛΚ. Καθε γραμμα κρυβει ενα ψηφιο, διαφορετικα γραμματα = διαφορετικα ψηφια.',
    'ΜΟΝΗ ΣΩΣΤΗ ΑΠΑΝΤΗΣΗ: 2178 x 4 = 8712. Κ=2, Λ=1, Μ=7, Ν=8, Ρ=4.',
    'Αν εχει βρει σωστα (2178 x 4 = 8712): Πως το σκεφτηκες; Μετα: Το βρηκες! Σε περιμενω αυριο!',
    'Αν δεν εχει βρει, hint 1: Κοιτα προσεκτικα τον αριθμο ΚΛΜΝ και το αποτελεσμα ΝΜΛΚ. Τι παρατηρεις;',
    'Αν παλι δεν βρει, hint 2: Το Ρ δεν μπορει να ειναι μεγαλο - αφου το ΚΛΜΝ ειναι τετραψηφιος και μετα τον πολλαπλασιασμο παραμενει τετραψηφιος, αρα το Ρ ειναι μικρο: 2, 3 η 4.',
    'Αν παλι δεν βρει, hint 3: Αν Ρ=4, δοκιμασε αριθμους που αρχιζουν απο 2, γιατι 2x4=8 αρα ο ανεστραμμενος αρχιζει απο 8 - που σημαινει ο αρχικος τελειωνει σε 8. Αρα ψαχνεις αριθμο της μορφης 2__8 x 4 = 8__2.',
    'Αν παλι δεν βρει, hint 4: Ψαχνεις αριθμο 2__8 x 4 = 8__2. Το δευτερο ψηφιο του 2__8 επι 4 πρεπει να δινει ως τελευταιο ψηφιο το τριτο ψηφιο του αποτελεσματος. Δοκιμασε: 2108, 2118, 2128... ποιος δινει ανεστραμμενο αποτελεσμα;',
    'Αν παλι δεν βρει: Η απαντηση ειναι 2178 x 4 = 8712. Κ=2, Λ=1, Μ=7, Ν=8, Ρ=4.',
  ].join(' ');

  try {
    const { messages } = req.body;
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': process.env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify({
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 220,
        system: SYSTEM_PROMPT,
        messages
      })
    });
    const data = await response.json();
    const reply = data.content
      .map(b => b.text || '')
      .join('')
      .replace(/\*\*/g, '')
      .replace(/\*/g, '');
    res.status(200).json({ reply });
  } catch (e) {
    res.status(500).json({ error: 'Internal error' });
  }
};
