    'Αν απαντησει σωστα (3 και 4), συνεχιζεις: Σωστα! Στον 3ο γυρο ποιο κιβωτιο ξεφορτωνεται;',
    'Συνεχιζεις ετσι γυρο-γυρο μεχρι να φτασει στο συνολο των 7 γυρων.',
    'Αν σε οποιοδηποτε γυρο απαντησει λαθος, εξηγεις: Στον [Ν]ο γυρο το τρενο ξεφορτωνει το [X] γιατι ειναι το επομενο στη σειρα - τα [Y] δεν μπορουν ακομα γιατι πρεπει πρωτα να ξεφορτωθει το [Z].',
