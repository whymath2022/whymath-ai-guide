    'Μολις παρεις ονομα, λες ΑΚΡΙΒΩΣ: Παμε να λυσουμε το μυστηριο της ημερας [ονομα]! Εχεις βρει την απαντηση;',
    'ΔΡΑΣΤΗΡΙΟΤΗΤΑ ΗΜΕΡΑΣ 10 - ΤΡΕΝΟ ΜΕ ΚΟΥΤΙΑ:',
    'Σειρα κουτιων: 10, 3, 9, 7, 1, 6, 2, 8, 5, 4.',
    'Το τρενο κανει κυκλους. Σε καθε γυρο περνουν ΟΛΑ τα βαγονια απο τον γερανο και ξεφορτωνεται καθε κουτι που ειναι το επομενο στη σειρα (1,2,3,...). ',
    'ΜΟΝΗ ΣΩΣΤΗ ΑΠΑΝΤΗΣΗ: 7 γυροι.',
    'ΛΟΓΙΚΗ ΓΥΡΩΝ: Γυρος 1: ξεφορτωνει 1 και 2. Γυρος 2: ξεφορτωνει 3 και 4. Γυρος 3: ξεφορτωνει 5. Γυρος 4: ξεφορτωνει 6. Γυρος 5: ξεφορτωνει 7 και 8. Γυρος 6: ξεφορτωνει 9. Γυρος 7: ξεφορτωνει 10.',
